const STORE_KEY = 'lang';
const hasDoc = () => typeof document !== 'undefined' && document !== null;
const valid = (code) => typeof code === 'string' && LANGS.includes(code);

let current = 'en';
let store = null;

function defaultStorage() {
  try { return typeof localStorage !== 'undefined' ? localStorage : null; } catch { return null; }
}
function defaultBrowser() {
  return typeof navigator !== 'undefined' && navigator ? (navigator.languages || [navigator.language]) : [];
}

// A valid saved choice wins; otherwise the first browser tag whose main part is one of ours; otherwise English.
export function pickLang({ saved = null, browser = [] } = {}) {
  if (valid(saved)) return saved;
  for (const tag of Array.isArray(browser) ? browser : []) {
    const main = String(tag || '').split('-')[0].toLowerCase();
    if (valid(main)) return main;
  }
  return 'en';
}

export function t(key, vars = {}, lang = current) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : m));
}

export function getLang() { return current; }

export function setLang(code) {
  current = valid(code) ? code : 'en';
  try { store?.setItem(STORE_KEY, current); } catch { /* storage full or blocked */ }
  if (hasDoc()) {
    document.documentElement.lang = current;
    applyStatic();
  }
  if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function' && typeof CustomEvent === 'function') {
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: current } }));
  }
}

export function initLang({ storage = defaultStorage(), browser = defaultBrowser() } = {}) {
  store = storage || null;
  let saved = null;
  try { saved = store?.getItem(STORE_KEY) ?? null; } catch { saved = null; }
  current = pickLang({ saved, browser });
  if (hasDoc()) {
    document.documentElement.lang = current;
    applyStatic();
  }
  return current;
}

// Re-labels the page: text, placeholders, aria-labels, and (only for keys fixed in this file) HTML.
export function applyStatic(root = hasDoc() ? document : null) {
  if (!root?.querySelectorAll) return;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
}
